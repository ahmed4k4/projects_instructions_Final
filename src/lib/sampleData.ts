/**
 * Offline demo catalogue.
 *
 * Used only when Supabase credentials are absent, so a fresh clone renders a
 * realistic, fully interactive UI before anyone touches the database. Once
 * `VITE_SUPABASE_URL` is set, every hook switches to live rows.
 */

type Seed = Omit<PCComponent, 'createdAt' | 'updatedAt' | 'isActive' | 'currency' | 'storeLinks'>;

const now = new Date('2026-01-12T10:00:00.000Z').toISOString();

/**
 * The rows below are USD list prices — that is how the Phase 1 catalogue was
 * authored and changing every literal would silently break the compatibility and
 * scoring tests that assert on them. They are converted to EGP once, here, so the
 * rest of the app only ever sees Egyptian pounds.
 */
const seed = (rows: Omit<Seed, 'stockStatus'>[]): PCComponent[] =>
  rows.map((row) => ({
    ...row,
    price: toEgp(row.price),
    currency: CURRENCY,
    stockStatus: 'in_stock',
    storeLinks: [],
    isActive: true,
    createdAt: now,
    updatedAt: now,
  }));

const cpu = (
  id: string,
  brand: string,
  model: string,
  price: number,
  specs: Record<string, unknown>,
  performanceScore: number,
): Omit<Seed, 'stockStatus'> => ({
  id,
  category: 'cpu',
  brand,
  model,
  name: `${brand} ${model}`,
  price,
  specs,
  performanceScore,
  powerDrawWatts: Number(specs.tdp),
  imageUrl: null,
});

