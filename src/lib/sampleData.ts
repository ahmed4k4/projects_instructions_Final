export function getSampleComponent(id: string): PCComponent | undefined {
  return sampleComponents.find((c) => c.id === id);
}

export function resolveSampleBuild(build: SampleBuild): PCComponent[] {
  return build.componentIds.map((id) => getSampleComponent(id)).filter((c): c is PCComponent => Boolean(c));
}
